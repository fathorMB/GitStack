// Command gen genera internal/security/routes.gen.go dalla dichiarazione di
// sicurezza di ogni operazione di api/openapi.yaml: `security` (operazione o
// globale), `x-required-scopes`, `x-required-permission` e `x-password-change-exempt`. È l'unico modo
// in cui il gateway conosce cosa richiede una rotta: niente tabelle scritte
// a mano che possano divergere dal contratto (la CI rigenera e confronta,
// vedi scripts/check-api-generated.sh).
//
// Le operazioni con tag `internal` e `git-internal` (interfaccia fra servizi) non entrano
// nella tabella: il gateway non le espone mai.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type document struct {
	Security []map[string][]string           `yaml:"security"`
	Paths    map[string]map[string]yaml.Node `yaml:"paths"`
}

type operation struct {
	OperationID          string                 `yaml:"operationId"`
	Tags                 []string               `yaml:"tags"`
	Security             *[]map[string][]string `yaml:"security"`
	RequiredScopes       []string               `yaml:"x-required-scopes"`
	PasswordChangeExempt string                 `yaml:"x-password-change-exempt"`
	RequiredPermission   string                 `yaml:"x-required-permission"`
}

var methods = map[string]string{
	"get": "GET", "put": "PUT", "post": "POST", "delete": "DELETE",
	"patch": "PATCH", "head": "HEAD", "options": "OPTIONS",
}

var coreTags = map[string]bool{"system": true, "resources": true, "repos": true, "issues": true}

var identityTags = map[string]bool{
	"auth": true, "users": true, "tokens": true, "ssh-keys": true,
	"organizations": true, "teams": true, "permissions": true,
}

type route struct {
	Method, Path, OperationID, Service string
	Public                             bool
	Credentials                        []string
	Scopes                             []string
	Exempt                             string
	Permission                         string
}

func main() {
	contract := flag.String("contract", "", "percorso di api/openapi.yaml")
	out := flag.String("out", "", "file Go da scrivere")
	flag.Parse()
	if *contract == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "uso: gen -contract api/openapi.yaml -out routes.gen.go")
		os.Exit(2)
	}
	if err := run(*contract, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(contractPath, outPath string) error {
	raw, err := os.ReadFile(contractPath)
	if err != nil {
		return err
	}
	var doc document
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return fmt.Errorf("contratto non valido: %w", err)
	}

	var routes []route
	for path, item := range doc.Paths {
		for key, node := range item {
			method, ok := methods[key]
			if !ok {
				continue // "parameters", "summary", ...
			}
			var op operation
			if err := node.Decode(&op); err != nil {
				return fmt.Errorf("%s %s: %w", method, path, err)
			}
			r, skip, err := build(doc, method, path, op)
			if err != nil {
				return err
			}
			if !skip {
				routes = append(routes, r)
			}
		}
	}
	sort.Slice(routes, func(i, j int) bool {
		if routes[i].Path != routes[j].Path {
			return routes[i].Path < routes[j].Path
		}
		return routes[i].Method < routes[j].Method
	})

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/security/gen from api/openapi.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package security\n\n")
	b.WriteString("// Routes è la dichiarazione di sicurezza di ogni operazione pubblica del\n// contratto, con il percorso senza prefisso di versione.\n")
	b.WriteString("var Routes = []Route{\n")
	for _, r := range routes {
		fmt.Fprintf(&b, "\t{Method: %q, Path: %q, OperationID: %q, Service: %s, Public: %t, Credentials: %s, Scopes: %s, Permission: %s, PasswordChangeExempt: %s},\n",
			r.Method, r.Path, r.OperationID, "Service"+strings.ToUpper(r.Service[:1])+r.Service[1:], r.Public,
			creds(r.Credentials), strs(r.Scopes), permission(r.Permission), exempt(r.Exempt))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(outPath, src, 0o644)
}

func build(doc document, method, path string, op operation) (route, bool, error) {
	where := method + " " + path
	if op.OperationID == "" {
		return route{}, false, fmt.Errorf("%s: operationId mancante", where)
	}
	var service string
	for _, tag := range op.Tags {
		switch {
		case tag == "internal" || tag == "git-internal":
			return route{}, true, nil
		case coreTags[tag]:
			service = "core"
		case identityTags[tag]:
			service = "identity"
		default:
			return route{}, false, fmt.Errorf("%s: tag %q sconosciuto: decidere a quale servizio va instradato e aggiungerlo al generatore", where, tag)
		}
	}
	if service == "" {
		return route{}, false, fmt.Errorf("%s: nessun tag", where)
	}

	reqs := doc.Security
	if op.Security != nil {
		reqs = *op.Security
	}
	r := route{Method: method, Path: path, OperationID: op.OperationID, Service: service, Scopes: op.RequiredScopes, Exempt: op.PasswordChangeExempt, Permission: op.RequiredPermission}
	if len(reqs) == 0 {
		if len(op.RequiredScopes) > 0 {
			return route{}, false, fmt.Errorf("%s: rotta pubblica con x-required-scopes", where)
		}
		if op.RequiredPermission != "" {
			return route{}, false, fmt.Errorf("%s: rotta pubblica con x-required-permission", where)
		}
		r.Public = true
		return r, false, nil
	}
	seen := map[string]bool{}
	for _, req := range reqs {
		for scheme := range req {
			var kind string
			switch scheme {
			case "bearerAuth":
				kind = "token"
			case "sessionCookie":
				kind = "session"
			default:
				return route{}, false, fmt.Errorf("%s: schema di sicurezza %q non gestito dal gateway", where, scheme)
			}
			if !seen[kind] {
				seen[kind] = true
				r.Credentials = append(r.Credentials, kind)
			}
		}
	}
	sort.Strings(r.Credentials)
	switch op.RequiredPermission {
	case "":
		// Le rotte di core su una risorsa ({resourceId}) devono dichiarare il
		// permesso: niente rotte aperte per dimenticanza. Quelle di identity
		// (grant, permesso effettivo) applicano il ruolo admin da sé.
		if service == "core" && strings.Contains(path, "{resourceId}") {
			return route{}, false, fmt.Errorf("%s: rotta su {resourceId} senza x-required-permission (read|write|admin)", where)
		}
	case "read", "write", "admin":
		if service != "core" {
			return route{}, false, fmt.Errorf("%s: x-required-permission è applicato dal gateway solo alle rotte di core", where)
		}
		if !strings.Contains(path, "{resourceId}") {
			return route{}, false, fmt.Errorf("%s: x-required-permission senza {resourceId} nel percorso", where)
		}
	default:
		return route{}, false, fmt.Errorf("%s: x-required-permission %q non valido (read|write|admin)", where, op.RequiredPermission)
	}
	switch r.Exempt {
	case "", "always", "self":
	default:
		return route{}, false, fmt.Errorf("%s: x-password-change-exempt %q non valido (always|self)", where, r.Exempt)
	}
	return r, false, nil
}

func creds(c []string) string {
	if len(c) == 0 {
		return "nil"
	}
	parts := make([]string, len(c))
	for i, k := range c {
		parts[i] = "Credential" + strings.ToUpper(k[:1]) + k[1:]
	}
	return "[]CredentialKind{" + strings.Join(parts, ", ") + "}"
}

func strs(s []string) string {
	if len(s) == 0 {
		return "nil"
	}
	parts := make([]string, len(s))
	for i, v := range s {
		parts[i] = fmt.Sprintf("%q", v)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

func permission(p string) string {
	switch p {
	case "read":
		return "PermissionRead"
	case "write":
		return "PermissionWrite"
	case "admin":
		return "PermissionAdmin"
	}
	return "PermissionNone"
}

func exempt(e string) string {
	switch e {
	case "always":
		return "ExemptAlways"
	case "self":
		return "ExemptSelf"
	}
	return "ExemptNever"
}
