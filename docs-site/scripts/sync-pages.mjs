// Copies the repository documents that belong to the public site into
// docs/admin/ with a Docusaurus front matter and links rewritten to site
// pages. The sources (docs/operations.md, docs/versioning.md, SECURITY.md)
// stay the single copy: the outputs are git-ignored and generated at build
// time. A source that disappears, or a link that leaves the repository,
// fails the build instead of publishing a broken page.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, join, posix, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '..');
const repo = resolve(site, '..');

const pages = [
  {src: 'docs/operations.md', out: 'docs/admin/operations.md', id: 'operations', title: 'Operations guide'},
  {src: 'docs/versioning.md', out: 'docs/admin/versioning.md', id: 'versioning', title: 'Versioning policy'},
  {src: 'SECURITY.md', out: 'docs/admin/security-policy.md', id: 'security-policy', title: 'Security policy'},
];

// Repository path of a document -> page of the site.
const sitePages = new Map(pages.map((p) => [p.src, `./${p.out.split('/').pop()}`]));
const repoUrl = 'https://github.com/fathorMB/GitStack/blob/main/';

function rewriteLinks(text, srcRel) {
  const srcDir = posix.dirname(srcRel);
  return text.replace(/\]\((?!https?:|mailto:|#|\/)([^)\s#]+)(#[^)\s]*)?\)/g, (_m, target, anchor = '') => {
    const abs = posix.normalize(posix.join(srcDir, target));
    if (abs.startsWith('..')) {
      throw new Error(`${srcRel}: link ${target} leaves the repository`);
    }
    const page = sitePages.get(abs);
    if (page) return `](${page}${anchor})`;
    // Any other file of the repository: link to it on GitHub.
    return `](${repoUrl}${abs}${anchor})`;
  });
}

for (const p of pages) {
  const raw = readFileSync(join(repo, p.src), 'utf8').replace(/\r\n/g, '\n');
  // Drop the first H1: the title comes from the front matter.
  const body = rewriteLinks(raw.replace(/^# .*\n+/, ''), p.src);
  const out =
    `---\nid: ${p.id}\ntitle: ${JSON.stringify(p.title)}\n---\n\n` +
    `<!-- Generated by scripts/sync-pages.mjs from ${p.src}. Do not edit. -->\n\n${body}`;
  const dest = join(site, p.out);
  mkdirSync(dirname(dest), {recursive: true});
  writeFileSync(dest, out);
  console.log(`sync-pages: ${p.src} -> docs-site/${p.out}`);
}
