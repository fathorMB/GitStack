// Package promptgen genera prompts_gen.go: i prompt MCP di `gs mcp` (M4) sono i
// flussi delle skills di skills/, non un testo scritto a mano. Un test del
// package mcp rigenera il file e fallisce se skills/ e prompts_gen.go divergono.
package promptgen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

// Arg è un argomento di un prompt.
type Arg struct {
	Name, Description string
	Required          bool
}

// Def lega un prompt MCP a una skill.
type Def struct {
	Name  string // nome del prompt, minuscolo con trattini bassi
	Skill string // cartella in skills/
	Title string
	Args  []Arg
}

// Defs sono i prompt di M4: issue fino alla PR, triage, review di PR.
var Defs = []Def{
	{
		Name: "ci_cycle", Skill: "gitstack-ci", Title: "Attendi e correggi la CI",
		Args: []Arg{
			{"repo", "Repository nella forma owner/nome.", true},
			{"run_id", "ID dell'esecuzione da seguire, se già avviata.", false},
		},
	},
	{
		Name: "issue_to_pr", Skill: "gitstack-issue-to-commit", Title: "Da una issue alla Pull Request",
		Args: []Arg{
			{"repo", "Repository nella forma owner/nome.", true},
			{"issue", "Numero della issue da implementare.", true},
		},
	},
	{
		Name: "issue_triage", Skill: "gitstack-issue-triage", Title: "Triage delle issue",
		Args: []Arg{
			{"repo", "Repository nella forma owner/nome.", true},
		},
	},
	{
		Name: "pr_review", Skill: "gitstack-pr-review", Title: "Review di una Pull Request",
		Args: []Arg{
			{"repo", "Repository nella forma owner/nome.", true},
			{"number", "Numero della Pull Request.", true},
		},
	},
}

// Skill è una skill letta da skills/<nome>/SKILL.md.
type Skill struct {
	Name, Description, Body string
}

// ReadSkill legge e separa frontmatter e corpo (a capo normalizzati a LF).
func ReadSkill(dir, name string) (Skill, error) {
	raw, err := os.ReadFile(filepath.Join(dir, name, "SKILL.md"))
	if err != nil {
		return Skill{}, err
	}
	src := strings.ReplaceAll(string(raw), "\r\n", "\n")
	if !strings.HasPrefix(src, "---\n") {
		return Skill{}, fmt.Errorf("%s: manca il frontmatter", name)
	}
	rest := src[4:]
	end := strings.Index(rest, "\n---\n")
	if end < 0 {
		return Skill{}, fmt.Errorf("%s: frontmatter non chiuso", name)
	}
	s := Skill{}
	for _, line := range strings.Split(rest[:end], "\n") {
		k, v, ok := strings.Cut(line, ":")
		if !ok {
			return Skill{}, fmt.Errorf("%s: riga di frontmatter non valida %q", name, line)
		}
		switch strings.TrimSpace(k) {
		case "name":
			s.Name = strings.TrimSpace(v)
		case "description":
			s.Description = strings.TrimSpace(v)
		}
	}
	if s.Name != name || s.Description == "" {
		return Skill{}, fmt.Errorf("%s: name o description del frontmatter non validi", name)
	}
	s.Body = strings.TrimSpace(rest[end+5:])
	return s, nil
}

// Generate produce il sorgente Go (package pkg) con la tabella Prompts.
func Generate(skillsDir, pkg string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by cli/cmd/promptgen from skills/ (SKILL.md); DO NOT EDIT.\n")
	b.WriteString("// Rigenera con: cd cli && go generate ./internal/mcp/...\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("// Prompts sono i prompt MCP (M4): i flussi delle skills di skills/.\n")
	b.WriteString("var Prompts = []Prompt{\n")
	for _, d := range Defs {
		s, err := ReadSkill(skillsDir, d.Skill)
		if err != nil {
			return nil, err
		}
		b.WriteString("\t{\n")
		fmt.Fprintf(&b, "\t\tName:        %q,\n", d.Name)
		fmt.Fprintf(&b, "\t\tTitle:       %q,\n", d.Title)
		fmt.Fprintf(&b, "\t\tSkill:       %q,\n", d.Skill)
		fmt.Fprintf(&b, "\t\tDescription: %q,\n", s.Description)
		b.WriteString("\t\tArguments: []PromptArgument{\n")
		for _, a := range d.Args {
			fmt.Fprintf(&b, "\t\t\t{Name: %q, Description: %q, Required: %t},\n", a.Name, a.Description, a.Required)
		}
		b.WriteString("\t\t},\n")
		fmt.Fprintf(&b, "\t\tBody: %q,\n", s.Body)
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
