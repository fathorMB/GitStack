package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestGenerateWritesCommandTree: la reference ha una pagina per la radice e
// per i sottocomandi, con il front matter di Docusaurus e senza data (due
// giri producono gli stessi byte).
func TestGenerateWritesCommandTree(t *testing.T) {
	a, b := t.TempDir(), t.TempDir()
	if err := generate(a); err != nil {
		t.Fatalf("generate: %v", err)
	}
	if err := generate(b); err != nil {
		t.Fatalf("generate (2): %v", err)
	}
	for _, name := range []string{"gs.md", "gs_issue.md", "gs_auth_login.md"} {
		got, err := os.ReadFile(filepath.Join(a, name))
		if err != nil {
			t.Fatalf("manca %s: %v", name, err)
		}
		if !strings.HasPrefix(string(got), "---\nid: ") {
			t.Errorf("%s senza front matter: %q", name, string(got[:20]))
		}
		if strings.Contains(string(got), "Auto generated by spf13/cobra") {
			t.Errorf("%s contiene la data di generazione", name)
		}
		other, err := os.ReadFile(filepath.Join(b, name))
		if err != nil || string(other) != string(got) {
			t.Errorf("%s non è deterministico", name)
		}
	}
}
